export function copy(locale: Locale): Dict {
  return locale === "en" ? en : pl
}

/** Polish plural bucket: 1 → one, 2–4 (not 12–14) → few, everything else → many. */
export function pluralKind(n: number, locale: Locale): "one" | "few" | "many" {
  if (n === 1) return "one"
  if (locale === "en") return "many"
  const mod10 = n % 10
  const mod100 = n % 100
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return "few"
  return "many"
}

export type T = (key: CopyKey, vars?: Record<string, string | number>) => string

/** t("key", { n: 3 }) for both server and client components. */
export function translator(locale: Locale): T {
  const dict = copy(locale)
  return (key, vars) => (vars ? fmt(dict[key], vars) : dict[key])
}

